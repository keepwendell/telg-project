const AuthAPI = {
  _key:'telg-auth',
  _read(){ try{ return JSON.parse(localStorage.getItem(this._key)||'null')||null; }catch(e){ return null; } },
  _write(a){ try{ localStorage.setItem(this._key, JSON.stringify(a)); }catch(e){} },
  async _hash(salt,pw){
    try{ const buf=await crypto.subtle.digest('SHA-256', new TextEncoder().encode(salt+'::'+pw)); return Array.from(new Uint8Array(buf)).map(b=>b.toString(16).padStart(2,'0')).join(''); }
    catch(e){ let h=0; const t=salt+'::'+pw; for(let i=0;i<t.length;i++) h=(h*31+t.charCodeAt(i))>>>0; return 'f'+h.toString(16); }
  },
  async register(a){
    const username=((a&&a.username)||'').trim(); const password=(a&&a.password)||'';
    if(!username) return {ok:false, error:L()['acc.needUser']};
    if(password.length<4) return {ok:false, error:L()['acc.pwShort']};
    if(this._read()) return {ok:false, error:L()['acc.hasAccount']};
    const salt=Math.random().toString(36).slice(2)+Date.now().toString(36);
    this._write({username, salt, passHash: await this._hash(salt,password), created_at:Date.now(), session:true});
    return {ok:true, user:{username}};
  },
  async login(a){
    const username=((a&&a.username)||'').trim(); const password=(a&&a.password)||'';
    const acc=this._read();
    if(!acc) return {ok:false, error:L()['acc.noAccount']};
    if(acc.username!==username) return {ok:false, error:L()['acc.wrongUser']};
    if((await this._hash(acc.salt,password))!==acc.passHash) return {ok:false, error:L()['acc.wrongPw']};
    acc.session=true; this._write(acc);
    return {ok:true, user:{username:acc.username}};
  },
  current(){ const a=this._read(); return (a&&a.session)?{username:a.username}:null; },
  exists(){ return !!this._read(); }
};
