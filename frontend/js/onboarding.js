async function surveyNext(){
  const t=L();
  const role = document.getElementById('sv-role').value.trim();
  const domain = document.getElementById('sv-domain').value.trim();
  const minutes = state.survey.minutes;
  const statusEl = document.getElementById('sv-status');
  if(!domain){ statusEl.innerHTML = statusHtml('err', t['sv.needDomain']); return; }
  if(!(minutes>0)){ statusEl.innerHTML = statusHtml('err', t['sv.needMin']); return; }
  state.survey.role=role; state.survey.domain=domain; state.survey.minutes=minutes;
  try{ localStorage.setItem('telg-profile-answers', JSON.stringify(state.survey)); }catch(e){}
  if(!state.llmOk){ state.gen=null; state.genLlmSnapshot=null; advanceTo(3); return; }
  const next = document.getElementById('ob-next');
  next.disabled = true;
  statusEl.innerHTML = statusHtml('busy', t['sv.generating']);
  try{
    const payload = { role, domain, language: state.survey.language, focus:'', minutes, llm_config: state.llm };
    state.gen = await apiFetch('/config/onboarding/generate', {method:'POST', headers:{'Content-Type':'application/json'}, body:JSON.stringify(payload)}, 120000);
    state.genLlmSnapshot = Object.assign({}, state.llm);
    state.llmChangedSinceGen = false;
    advanceTo(3);
  }catch(e){
    statusEl.innerHTML = statusHtml('err', t['sv.genFail']+': '+e.message);
  }finally{
    next.disabled = false;
  }
}
