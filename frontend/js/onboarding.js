async function apiFetch(path, opts, timeoutMs){
  const ctrl = new AbortController();
  const timer = setTimeout(()=>ctrl.abort(), timeoutMs||60000);
  let res;
  try{ res = await fetch(CONFIG.apiBase+path, Object.assign({signal:ctrl.signal}, opts||{})); }
  catch(e){ clearTimeout(timer); throw new Error('Cannot reach backend at '+CONFIG.apiBase+' — start FastAPI (backend/main.py) on port 8000'); }
  clearTimeout(timer);
  const ct=(res.headers.get('content-type')||'').toLowerCase();
  if(!ct.includes('application/json')){ throw new Error('Backend returned non-JSON ('+res.status+') — open via http://127.0.0.1:8000, not a static server'); }
  const data = await res.json();
  if(!res.ok){ const msg = data && data.detail ? (typeof data.detail==='string'?data.detail:JSON.stringify(data.detail)) : ('HTTP '+res.status); throw new Error(msg); }
  return data;
}
